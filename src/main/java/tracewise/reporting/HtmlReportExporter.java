package tracewise.reporting;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import tracewise.domain.Transaction;

/** The report as a printable HTML page; every value from the case or the analyst is escaped. */
public class HtmlReportExporter implements ReportExporter {

    static final String NOT_SUBMITTED = "Generated by TraceWise for internal review. Not submitted to FINTRAC.";

    @Override
    public ExportFormat format() {
        return ExportFormat.HTML;
    }

    @Override
    public Path export(StrReport report, Path dir) throws IOException {
        var rows = new StringBuilder();
        for (Transaction t : report.transactions()) {
            rows.append("<tr>").append(cell(t.id())).append(cell(t.timestamp().toString()))
                    .append(cell(t.senderAccountId())).append(cell(t.receiverAccountId()))
                    .append("<td class=\"num\">").append(esc(t.amountCad().toPlainString())).append("</td>")
                    .append(cell(t.originalAmount().toPlainString() + " " + t.currency())).append(cell(t.channel().name()))
                    .append(cell(t.counterpartyCountry() == null ? "" : t.counterpartyCountry())).append("</tr>\n");
        }
        String html = """
                <!DOCTYPE html>
                <html lang="en"><head><meta charset="utf-8">
                <title>Suspicious Transaction Report %1$s</title>
                <style>
                body { font-family: Georgia, serif; max-width: 60rem; margin: 2rem auto; color: #111; }
                table { border-collapse: collapse; width: 100%%; font-size: 0.9rem; }
                th, td { border: 1px solid #999; padding: 0.3rem 0.5rem; text-align: left; }
                td.num { text-align: right; }
                .text { white-space: pre-wrap; }
                .note { color: #555; font-size: 0.85rem; }
                </style></head><body>
                <h1>Suspicious Transaction Report</h1>
                <p>Case %1$s. Status: %2$s. Finalised: %3$s.</p>
                <h2>Part A: Subject account</h2>
                <p>%4$s</p>
                <h2>Part B: Transactions</h2>
                <table><tr><th>Transaction</th><th>Time (UTC)</th><th>From</th><th>To</th><th>Amount (CAD)</th>
                <th>Original amount</th><th>Channel</th><th>Country</th></tr>
                %5$s</table>
                <h2>Part C: Grounds for suspicion</h2>
                <p class="text">%6$s</p>
                <h2>Part D: Actions taken</h2>
                <p class="text">%7$s</p>
                <p class="note">%8$s</p>
                </body></html>
                """.formatted(esc(report.caseId()), report.status().name(),
                report.finalisedAt() == null ? "not yet" : report.finalisedAt().toString(), esc(report.subjectAccountId()),
                rows, esc(report.groundsForSuspicion()), esc(report.actionsTaken()), NOT_SUBMITTED);
        Path file = dir.resolve(report.caseId() + "-STR.html");
        Files.writeString(file, html);
        return file;
    }

    private static String cell(String value) {
        return "<td>" + esc(value) + "</td>";
    }

    private static String esc(String s) {
        return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\"", "&quot;")
                .replace("'", "&#39;");
    }
}
